import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import { removeMagenta } from "./palette.mjs";

const sharp = createRequire(new URL("../../apps/server/package.json", import.meta.url))("sharp");
const [assetId, jobId] = process.argv.slice(2);
const [left = 2, top = 2, width = 252, height = 252] = process.argv.slice(4).map(Number);
if (![left, top, width, height].every(Number.isInteger) || width > 256 || height > 256 || width < 1 || height < 1) throw new Error("Invalid native crop");
if (!/^[a-z0-9-]+$/.test(assetId) || !/^[a-f0-9-]+$/.test(jobId)) throw new Error("Invalid source identifiers");
const response = await fetch(`https://api.pixellab.ai/mcp/images/${jobId}/download`);
if (!response.ok) throw new Error(`PixelLab download failed: ${response.status}`);
const input = Buffer.from(await response.arrayBuffer());
const directory = new URL(`./sources/${assetId}/`, import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL("pro-sheet.png", directory), input);
const { data, info } = await sharp(input).extract({ left, top, width, height }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
removeMagenta(data);
const paddingX = Math.floor((256 - width) / 2);
const paddingY = Math.floor((256 - height) / 2);
const reference = await sharp(data, { raw: info }).extend({ top: paddingY, bottom: 256 - height - paddingY, left: paddingX, right: 256 - width - paddingX, background: { r: 0, g: 0, b: 0, alpha: 0 } }).png().toBuffer();
await writeFile(new URL("rotation-source.png", directory), reference);
process.stdout.write(reference.toString("base64"));
